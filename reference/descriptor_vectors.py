"""Generate public descriptor fixtures and deterministic request/result vectors.

Large PQ keys are stored once. Requests are regenerated by cases(); the vector
file pins each exact request line and complete response by SHA256, plus useful
descriptor fields. No test private key or cryptographic signing is involved.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import random

import descriptor as d

VECTOR_FILE = Path(__file__).with_name("descriptor_vectors.json")


def fixture(index):
    return hashlib.shake_256(b"gnb-descriptor-public-fixture-v1" + index.to_bytes(4, "little")).digest(d.RAW_KEY_BYTES).hex()


def fixtures():
    raw = {f"raw{i}": fixture(i) for i in range(8)}
    return {**raw, "enveloped0": "b10c0100" + raw["raw0"], "raw_magic": "b10cffff" + raw["raw0"][8:]}


def cases():
    """Yield (name, literal JSON request line, required acceptance verdict)."""
    keys = fixtures()
    k0, k1 = keys["raw0"], keys["raw1"]

    def row(name, request, valid):
        return name, d.compact(request), valid

    def body(network, expression):
        return f"gnbd1({network},{expression})"

    def policy(count=1, threshold=1, after=0, older=0):
        return f"policy({threshold},{after},{older},{','.join(keys[f'raw{i}'] for i in range(count))})"

    expressions = {"pkh-raw": f"pkh({k0})", "pkh-envelope": f"pkh({keys['enveloped0']})", "pkh-magic-raw": f"pkh({keys['raw_magic']})", "policy-1": policy(), "policy-2of3": policy(3, 2, 17500, 144), "policy-u32-max-7": policy(7, 7, 0xFFFFFFFF, 0xFFFFFFFF), "policy-mixed-encodings": f"policy(2,0,0,{k0},b10c0100{k1})", "policy-reordered": f"policy(2,17500,144,{keys['raw2']},{k1},{k0})"}
    for count in (2, 3, 4):
        expressions[f"tree-{count}"] = "tree(" + ",".join(policy(i + 1, 1, i, i * 17) for i in range(count)) + ")"
    expressions["tree-largest-4x7"] = "tree(" + ",".join(policy(7, 7, 0xFFFFFFFF, i) for i in range(4)) + ")"
    descriptors = {}
    for network in d.NETWORKS:
        for label, expression in expressions.items():
            text = body(network, expression)
            descriptor = d.add_checksum(text)
            descriptors[network, label] = descriptor
            yield row(f"{network}/{label}/create", {"action": "create", "network": network, "body": text}, True)
            yield row(f"{network}/{label}/inspect", {"op": "descriptor", "action": "inspect", "network": network, "descriptor": descriptor}, True)
        # PF-4: a raw key and its envelope are one signer; no policy or tree
        # branch may list both in a descriptor being created. An existing one
        # (an earlier release created it) is still inspected and restored,
        # flagged with twin_key_encodings.
        twin = f"policy(2,0,0,{k0},{keys['enveloped0']})"
        twins = {"policy-twin-encoding": body(network, twin), "tree-twin-encoding": body(network, f"tree({policy()},{twin})")}
        for label, text in twins.items():
            yield row(f"{network}/{label}/create", {"action": "create", "network": network, "body": text}, False)
            yield row(f"{network}/{label}/inspect", {"op": "descriptor", "action": "inspect", "network": network, "descriptor": d.add_checksum(text)}, True)
        restored = [descriptors[network, "pkh-raw"], d.add_checksum(twins["policy-twin-encoding"]), d.add_checksum(twins["tree-twin-encoding"])]
        yield row(f"{network}/export-twin-encoding", {"action": "export", "network": network, "descriptors": restored}, True)
        yield row(f"{network}/import-twin-encoding", {"action": "import", "network": network, "bundle": d.compact({"format": d.POOL_FORMAT, "network": network, "descriptors": restored})}, True)
        ds = [descriptors[network, label] for label in ("pkh-raw", "pkh-envelope", "policy-2of3", "tree-3")]
        yield row(f"{network}/export", {"action": "export", "network": network, "descriptors": ds}, True)
        bundle = d.compact({"format": d.POOL_FORMAT, "network": network, "descriptors": ds})
        yield row(f"{network}/import", {"action": "import", "network": network, "bundle": bundle}, True)
        yield row(f"{network}/pool", {"action": "pool", "network": network, "public_keys": [k0, keys["enveloped0"], k1]}, True)
        yield row(f"{network}/export-duplicate", {"action": "export", "network": network, "descriptors": ds + [ds[0]]}, False)
        wrong_network = "testnet" if network == "mainnet" else "mainnet"
        yield row(f"{network}/inspect-wrong-network", {"action": "inspect", "network": wrong_network, "descriptor": ds[0]}, False)
        yield row(f"{network}/import-wrong-network", {"action": "import", "network": wrong_network, "bundle": bundle}, False)
        yield row(f"{network}/mixed-pool", {"action": "export", "network": network, "descriptors": ds + [d.add_checksum(body(wrong_network, f'pkh({k1})'))]}, False)

    valid_body = body("mainnet", expressions["pkh-raw"])
    valid_desc = descriptors["mainnet", "pkh-raw"]
    invalid_bodies = {
        "uppercase": valid_body.upper(), "leading-space": " " + valid_body, "trailing-space": valid_body + " ", "embedded-space": valid_body.replace("pkh(", "pkh( "), "newline": valid_body + "\n", "tab": valid_body.replace("pkh(", "pkh(\t"), "trailing-data": valid_body + "x", "extra-close": valid_body + ")", "missing-close": valid_body[:-1], "create-with-checksum": valid_desc, "private-marker": body("mainnet", "pkh(xprv0123456789)"), "xpub": body("mainnet", "pkh(xpub0123456789)"), "path": body("mainnet", f"pkh({k0}/0)"), "wildcard": body("mainnet", f"pkh({k0}*)"), "origin": body("mainnet", f"pkh([deadbeef]{k0})"), "non-ascii": valid_body.replace("gnbd", "gnbḋ"), "unknown-version": valid_body.replace("gnbd1", "gnbd2"), "unknown-network": valid_body.replace("mainnet", "regtest"), "empty-key": body("mainnet", "pkh()"), "short-key": body("mainnet", f"pkh({k0[:-2]})"), "long-key": body("mainnet", f"pkh({k0}00)"), "odd-hex": body("mainnet", f"pkh({k0[:-1]})"), "upper-hex": body("mainnet", f"pkh({k0.upper()})"), "bad-hex": body("mainnet", f"pkh(g{k0[1:]})"), "wrong-suite": body("mainnet", f"pkh(b10c0200{k0})"), "wrong-magic": body("mainnet", f"pkh(b20c0100{k0})"), "nested-envelope": body("mainnet", f"pkh(b10c0100b10c0100{k0})"), "nested-tree": body("mainnet", f"tree(tree({policy()},{policy()}),{policy()})"), "descriptor-limit": "x" * d.MAX_DESCRIPTOR_BYTES, "descriptor-over-limit": "x" * (d.MAX_DESCRIPTOR_BYTES + 1),
    }
    for threshold in ("0", "2", "01", "+1", "-1", "1.0", "4294967296", "99999999999999999999"):
        invalid_bodies[f"threshold-{threshold}"] = body("mainnet", f"policy({threshold},0,0,{k0})")
    for index, (after, older) in enumerate((("01", "0"), ("0", "01"), ("-1", "0"), ("0", "4294967296"), ("4294967296", "0"))):
        invalid_bodies[f"timelock-{index}"] = body("mainnet", f"policy(1,{after},{older},{k0})")
    invalid_bodies.update({"policy-empty": body("mainnet", "policy(1,0,0)"), "policy-duplicate": body("mainnet", f"policy(1,0,0,{k0},{k0})"), "policy-8": body("mainnet", policy(8)), "tree-0": body("mainnet", "tree()"), "tree-1": body("mainnet", f"tree({policy()})"), "tree-5": body("mainnet", "tree(" + ",".join([policy()] * 5) + ")")})
    for label, value in invalid_bodies.items():
        yield row("grammar/" + label, {"action": "create", "network": "mainnet", "body": value}, False)
        # A correct checksum is not permission to bypass the same grammar on
        # inspection. Some invalid text has no representation in BIP380.
        try:
            checksummed = d.add_checksum(value)
        except ValueError:
            continue
        yield row("grammar-inspect/" + label, {"action": "inspect", "network": "mainnet", "descriptor": checksummed}, False)

    for label, value in {"absent": valid_body, "short": valid_desc[:-1], "long": valid_desc + "q", "double": valid_desc.replace("#", "##"), "bad-symbol": valid_desc[:-1] + "b", "changed-body": valid_desc.replace("mainnet", "testnet"), "extra-text": valid_desc + "x", "space": valid_desc + " "}.items():
        yield row("checksum/" + label, {"action": "inspect", "network": "mainnet", "descriptor": value}, False)
    rng = random.Random(38020261016)
    for index in range(32):
        pos = rng.randrange(len(valid_desc))
        replacement = "0" if valid_desc[pos] != "0" else "1"
        mutated = valid_desc[:pos] + replacement + valid_desc[pos + 1:]
        yield row(f"checksum/single-substitution-{index}", {"action": "inspect", "network": "mainnet", "descriptor": mutated}, False)

    controls = {
        "create": {"action": "create", "network": "mainnet", "body": valid_body},
        "inspect": {"action": "inspect", "network": "mainnet", "descriptor": valid_desc},
        "export": {"action": "export", "network": "mainnet", "descriptors": [valid_desc]},
        "import": {"action": "import", "network": "mainnet", "bundle": d.compact({"format": d.POOL_FORMAT, "network": "mainnet", "descriptors": [valid_desc]})},
        "pool": {"action": "pool", "network": "mainnet", "public_keys": [k0]},
    }
    for action, control in controls.items():
        for field in control:
            yield row(f"envelope/{action}/missing-{field}", {key: value for key, value in control.items() if key != field}, False)
            for index, value in enumerate((None, False, 1, [], {})):
                # The list is the right type only for export/pool, but empty is invalid.
                yield row(f"envelope/{action}/{field}-type-{index}", {**control, field: value}, False)
        yield row(f"envelope/{action}/unknown-field", {**control, "extra": None}, False)
        for index, op in enumerate((None, False, 1, [], {}, "pay", "wipe")):
            yield row(f"envelope/{action}/op-{index}", {**control, "op": op}, False)
        line = d.compact(control)
        yield f"envelope/{action}/duplicate-network", line[:-1] + ',"network":"mainnet"}', False
    for index, request in enumerate((None, [], "descriptor", 1, False)):
        yield row(f"envelope/not-object-{index}", request, False)
    for index, line in enumerate(("{", "{}x", "NaN", '{"action":NaN}', '{"op":"descriptor","op":"descriptor"}')):
        yield f"envelope/invalid-json-{index}", line, False

    bundle = controls["import"]["bundle"]
    parsed = json.loads(bundle)
    reordered = {"descriptors": parsed["descriptors"], "network": "mainnet", "format": d.POOL_FORMAT}
    yield row("pool/reordered-and-pretty", {**controls["import"], "bundle": json.dumps(reordered, indent=2)}, True)
    yield row("pool/escaped-string", {**controls["import"], "bundle": bundle.replace("gnbd1", "\\u0067nbd1")}, True)
    for field in ("format", "network", "descriptors"):
        parsed = json.loads(bundle)
        yield row(f"pool/missing-{field}", {**controls["import"], "bundle": d.compact({key: value for key, value in parsed.items() if key != field})}, False)
        yield row(f"pool/duplicate-{field}", {**controls["import"], "bundle": bundle[:-1] + "," + d.compact(field) + ":" + d.compact(parsed[field]) + "}"}, False)
    for label, value in {"unknown-field": bundle[:-1] + ',"extra":false}', "format": bundle.replace(d.POOL_FORMAT, "gnb-watch-only-v2"), "trailing": bundle + "x", "empty": "{}", "null": "null", "array": "[]", "nan": bundle[:-1] + ',"extra":NaN}', "bytes-exact": bundle + " " * (d.MAX_POOL_BYTES - len(bundle)), "bytes-over": bundle + " " * (d.MAX_POOL_BYTES - len(bundle) + 1)}.items():
        yield row("pool/" + label, {**controls["import"], "bundle": value}, label == "bytes-exact")
    for count in (0, 64, 65):
        yield row(f"pool/count-{count}", {"action": "pool", "network": "mainnet", "public_keys": [fixture(i) for i in range(count)]}, count == 64)
    yield row("pool/duplicate-key", {"action": "pool", "network": "mainnet", "public_keys": [k0, k0]}, False)
    yield row("pool/bad-key-type", {"action": "pool", "network": "mainnet", "public_keys": [None]}, False)
    # Unique large trees pass per-descriptor bounds but exceed the pool byte cap.
    huge = [d.add_checksum(body("mainnet", "tree(" + ",".join(policy(7, 7, i * 4 + j, j) for j in range(4)) + ")")) for i in range(5)]
    yield row("pool/export-byte-limit", {"action": "export", "network": "mainnet", "descriptors": huge}, False)


def vectors():
    rows = []
    for name, line, accepted in cases():
        actual = d.oracle_line(line)
        if actual["ok"] != accepted:
            raise AssertionError("reference disagrees with frozen acceptance: " + name)
        row = {"name": name, "accepted": accepted, "request_sha256": hashlib.sha256(line.encode()).hexdigest(), "response_sha256": hashlib.sha256(d.compact(actual).encode()).hexdigest()}
        if accepted and "descriptor" in actual["result"]:
            info = actual["result"]
            row.update({key: info[key] for key in ("network", "kind", "script_pubkey", "address", "bech32m", "requires_policy_tree_activation", "twin_key_encodings") if key in info})
            row["checksum"] = info["descriptor"][-8:]
        rows.append(row)
    return {"format": "gnb-descriptor-reference-v1", "fixture_note": "Synthetic public byte shapes only; no proof of key possession or spendability.", "public_keys": fixtures(), "cases": rows}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = json.dumps(vectors(), indent=2, ensure_ascii=True) + "\n"
    if args.check:
        if VECTOR_FILE.read_text() != text:
            raise SystemExit("descriptor vectors differ; inspect before regenerating")
        print("descriptor vectors: reproducible")
    else:
        VECTOR_FILE.write_text(text)
        print("wrote", VECTOR_FILE)


if __name__ == "__main__":
    main()
